//go:build ignore

// Feature : `//go:build ignore` - a file that is never part of the package
//
//	build but must still be valid Go (commonly a generator run via
//	`go run excluded_by_ignore_tag.go`)
//
// Version : Go 1.17+ syntax (`// +build ignore` before that)
// Spec    : cmd/go "Build constraints" (any unknown tag such as "ignore"
//
//	evaluates to false)
//
// EXPECTED:
//   - Syntax parser                        -> PASS
//   - `go build ./...` / package loaders   -> file EXCLUDED
//   - `go run excluded_by_ignore_tag.go`   -> runs (explicit file list
//     overrides build constraints)
//
// Parser edge cases: a tool that reports "duplicate main" or "unused file"
// for files like this is mishandling build constraints.
package main

import "fmt"

//go:generate echo "go:generate directives are commonly found in ignored generator files"

func main() {
	tables := map[string][]int{"squares": nil, "cubes": nil}
	for i := 1; i <= 5; i++ {
		tables["squares"] = append(tables["squares"], i*i)
		tables["cubes"] = append(tables["cubes"], i*i*i)
	}
	fmt.Println("// Code generated by excluded_by_ignore_tag.go; DO NOT EDIT.")
	fmt.Printf("var Squares = %#v\nvar Cubes = %#v\n", tables["squares"], tables["cubes"])
}
